def _door_kick_plate_material(steel):
    """Satin steel with baked indirect reflection for the envmap-less room.

    Retain the lever's metallic BRDF for direct highlights. The emission
    texture represents reflected room fill, not a luminous light fixture.
    Only the opted-in plate consumes it; shared steel stays unchanged.
    """
    import bpy  # type: ignore[import-not-found]
    import math

    mat = steel.copy()
    mat.name = "openclinxr_door_kick_plate_steel"
    image = bpy.data.images.new("kick_plate_baked_reflection", width=128, height=64)
    pixels = []
    for y in range(64):
        for x in range(128):
            u, v = x / 127, y / 63
            highlight = math.exp(-((u - 0.42) / 0.32) ** 2)
            brush = 0.006 * math.sin(y * 2.4)
            value = 0.42 + 0.18 * highlight + 0.04 * v + brush
            pixels.extend((value * 0.97, value * 0.99, value, 1.0))
    image.pixels.foreach_set(pixels)
    image.pack()
    nt = mat.node_tree
    bsdf = next(node for node in nt.nodes if node.type == "BSDF_PRINCIPLED")
    tex = nt.nodes.new("ShaderNodeTexImage")
    tex.image = image
    uv = nt.nodes.new("ShaderNodeTexCoord")
    nt.links.new(uv.outputs["UV"], tex.inputs["Vector"])
    nt.links.new(tex.outputs["Color"], bsdf.inputs["Emission Color"])
    bsdf.inputs["Emission Strength"].default_value = 1.5
    return mat


def _assign_face_uv(obj, u_axis: int, v_axis: int,
                    u_bounds: tuple[float, float] | None = None,
                    v_bounds: tuple[float, float] | None = None) -> None:
    """Map a box by world axes, optionally against shared face bounds."""
    mesh = obj.data
    uv_layer = mesh.uv_layers.new(name="UVMap")
    coords = [obj.matrix_world @ vertex.co for vertex in mesh.vertices]
    u0, u1 = (u_bounds if u_bounds is not None else
              (min(v[u_axis] for v in coords), max(v[u_axis] for v in coords)))
    v0, v1 = (v_bounds if v_bounds is not None else
              (min(v[v_axis] for v in coords), max(v[v_axis] for v in coords)))
    for poly in mesh.polygons:
        for loop_index in poly.loop_indices:
            co = coords[mesh.loops[loop_index].vertex_index]
            uv_layer.data[loop_index].uv = (
                (co[u_axis] - u0) / max(u1 - u0, 1e-9),
                (co[v_axis] - v0) / max(v1 - v0, 1e-9),
            )


