def _world_bbox(obj) -> dict:
    """World-space AABB of a mesh object (Blender runtime only)."""
    import bpy  # type: ignore[import-not-found]

    mins = [float("inf")] * 3
    maxs = [float("-inf")] * 3
    for v in obj.data.vertices:
        wv = obj.matrix_world @ v.co
        for i in range(3):
            mins[i] = min(mins[i], wv[i])
            maxs[i] = max(maxs[i], wv[i])
    return {"min": mins, "max": maxs}


def _lite_opening_from_mesh(obj) -> dict | None:
    """Measured vision-lite rim loop when the leaf carries a sane one.

    Returns the smallest boundary-edge loop bbox covering less than 30% of
    the leaf face (a vision-lite rim), or None. Post-simplify leaves carry
    hundreds of micro-boundary loops and no clean rim (measured seed-205:
    770 loops, largest 41 edges), so this routinely reads as None and the
    caller falls back to the recipe fractions.
    Deterministic.
    """
    import bmesh  # type: ignore[import-not-found]
    import bpy  # type: ignore[import-not-found]

    mesh = obj.data
    bm = bmesh.new()
    try:
        bm.from_mesh(mesh)
        bedges = [e for e in bm.edges if e.is_boundary]
        if not bedges:
            return None
        adj: dict[int, list[int]] = {}
        for e in bedges:
            a, b = (v.index for v in e.verts)
            adj.setdefault(a, []).append(b)
            adj.setdefault(b, []).append(a)
        seen: set[int] = set()
        loops: list[list[int]] = []
        for start in adj:
            if start in seen:
                continue
            stack = [start]
            seen.add(start)
            comp = []
            while stack:
                v = stack.pop()
                comp.append(v)
                for w in adj.get(v, []):
                    if w not in seen:
                        seen.add(w)
                        stack.append(w)
            loops.append(comp)
        coords = []
        for v in mesh.vertices:
            coords.append(obj.matrix_world @ v.co)
        box = _world_bbox(obj)
        extents = [box["max"][i] - box["min"][i] for i in range(3)]
        thin = min(range(3), key=lambda i: extents[i])
        face_axes = [i for i in range(3) if i != thin]
        face_area = extents[face_axes[0]] * extents[face_axes[1]]
        mw = obj.matrix_world
        for comp in sorted(loops, key=len, reverse=True):
            us = [(mw @ mesh.vertices[i].co)[face_axes[0]] for i in comp]
            vs = [(mw @ mesh.vertices[i].co)[face_axes[1]] for i in comp]
            area = (max(us) - min(us)) * (max(vs) - min(vs))
            if area < 0.3 * face_area:
                return {
                    "thinAxis": thin,
                    "uAxis": face_axes[0],
                    "vAxis": face_axes[1],
                    "u0": min(us), "u1": max(us),
                    "v0": min(vs), "v1": max(vs),
                    "depthCenter": (box["min"][thin] + box["max"][thin]) / 2,
                    "depth": extents[thin],
                }
        return None
    finally:
        bm.free()


def _furnish_ward_door(recipe: dict, palette: dict, room_center: list,
                       casing_rgb: tuple = DOOR_CASING_RGB) -> dict:
    """Glass + lite frame + hinges + casing repaint (Blender runtime only).

    The lite rect comes from the deterministic recipe options.door.lite
    fractions mapped exactly like the factory (mirror + margin): the
    Infinigen lite IS a real through-opening (verified seed-205 via the
    glass-attribute bbox), but simplify shreds its rim into hundreds of
    micro-boundary loops, so no measured rim is usable for placement. A
    sane measured rim only cross-checks (recorded as rimCheck, never
    placed). Fail closed when the fractions/margin are absent or the leaf
    is not door-like: a ward door without a vision panel re-creates the
    defect this slice fixes.
    """
    import bpy  # type: ignore[import-not-found]
    import re

    leaf_re = re.compile(r"\.door_leaf(_\d+)?$")
    leaves = [obj for obj in bpy.data.objects
              if obj.type == "MESH" and leaf_re.search(obj.name)]
    if not leaves:
        raise SystemExit("room_clinic_finish: ward door furniture needs a kept door leaf")
    options = recipe.get("options")
    door_opt = options.get("door") if isinstance(options, dict) else None
    hinge_side = door_opt.get("hingeSide") if isinstance(door_opt, dict) else None
    lite_frac = door_opt.get("lite") if isinstance(door_opt, dict) else None
    lite_margin = door_opt.get("margin") if isinstance(door_opt, dict) else None
    kick_plate = door_opt.get("kickPlate", False) if isinstance(door_opt, dict) else False
    if not isinstance(kick_plate, bool):
        raise SystemExit("room_clinic_finish: door.kickPlate must be boolean")

    glass_m = _door_glass_material()
    steel_m = _door_steel_material()
    kick_plate_m = _door_kick_plate_material(steel_m) if kick_plate else None
    facing_m = _photo_uv_material(
        "openclinxr_finish_door_facing", DOOR_LEAF_FILE, 0.48,
        normal_filename=DOOR_NORMAL_FILE,
        roughness_filename=DOOR_ROUGHNESS_FILE)
    casing_m = _door_casing_material(casing_rgb,
                                     float(palette.get("roughness", 0.85)))
    reveal_m = _door_reveal_material()
    casing_re = re.compile(r"\.door_casing(_\d+)?$")
    repainted: list[str] = []
    for obj in bpy.data.objects:
        if obj.type != "MESH" or not casing_re.search(obj.name):
            continue
        mesh = obj.data
        if len(mesh.materials) == 0:
            mesh.materials.append(casing_m)
        else:
            for index in range(len(mesh.materials)):
                mesh.materials[index] = casing_m
        repainted.append(obj.name)

    furnished: dict = {"glass": [], "frame": [], "hinges": [], "casing": repainted,
                       "casingFaces": [], "reveals": [],
                       "opening": None, "openingSource": None, "handle": None,
                       "lock": None, "hingeSideUsed": None, "facing": [],
                       "transom": None, "kickPlate": None}

    def new_cylinder(name: str, center: list, thin_axis: int, radius: float,
                     z0: float, z1: float, mat: object, segments: int = 16) -> object:
        """Straight prism along a world axis with ngon caps (Blender runtime)."""
        import bpy  # type: ignore[import-not-found]
        import math

        mesh = bpy.data.meshes.new(name + "_mesh")
        obj = bpy.data.objects.new(name, mesh)
        bpy.context.scene.collection.objects.link(obj)
        obj["openClinXrFinishDecoration"] = True
        others = [i for i in range(3) if i != thin_axis]
        ring0, ring1 = [], []
        for k in range(segments):
            a = 2 * math.pi * k / segments
            base = list(center)
            base[others[0]] += radius * math.cos(a)
