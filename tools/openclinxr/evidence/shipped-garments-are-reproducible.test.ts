const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = pathResolve(HERE, "../../..");

const LIBRARY_BODIES = [
  "apps/ui-xr/public/xr-assets/humanoids/candidates/body-param-adult_lean_female-library.glb",
  "apps/ui-xr/public/xr-assets/humanoids/candidates/body-param-adult_heavy_male-library.glb",
] as const;

/** Where third-party garment sources are cached. */
const GARMENT_CACHE = join(REPO_ROOT, ".openclinxr-local/provider-cache/garments");

/** Meshes generated by a script in this repo — reproducible without any third-party source. */
const PROCEDURAL_GENERATORS: ReadonlyArray<{ meshPrefix: string; generator: string }> = [
  {
    meshPrefix: "openclinxr_footwear_",
    generator: "tools/openclinxr/asset-pipeline/makeclothes/embed_library_footwear.py",
  },
  // #310/#322: `makeclothes_library_civilian_shirt_*` is a DETERMINISTIC cover shell built from
  // the body surface by the stage script (#275/#277) — the same procedural class as footwear,
  // never fitted from a third-party .mhclo. #322 routed the family/casual layers to the fitted
  // CC0 `toigo_basic_tucked_t-shirt`, so neither shipped library body carries the shell today;
  // the entry stays because the mechanism survives for hospital_gown / open_cardigan, which
  // still have no .mhclo in any cached pack. Its `makeclothes_library_` prefix is a #275 naming
  // artifact; the prefix check must run before the library check so the contract measures fitted
  // library garments, not in-repo shells.
  {
    meshPrefix: "makeclothes_library_civilian_shirt_",
    generator: "tools/openclinxr/asset-pipeline/makeclothes/body_param_stage.py",
  },
];

/** Fitted third-party garments carry this prefix and must resolve to a cached `.mhclo`. */
const LIBRARY_GARMENT_PREFIX = "makeclothes_library_";

const io = new NodeIO();

function everyMhcloStem(): Set<string> {
  const stems = new Set<string>();
  const walk = (dir: string): void => {
    if (!existsSync(dir)) return;
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (entry.toLowerCase().endsWith(".mhclo")) {
        stems.add(entry.slice(0, -".mhclo".length).toLowerCase().replaceAll("-", "_"));
      }
    }
  };
  walk(GARMENT_CACHE);
  return stems;
}

type GarmentMesh = { body: string; mesh: string; triangles: number; kind: "library" | "procedural" | "other" };

async function garmentMeshes(rel: string): Promise<GarmentMesh[]> {
  const doc = await io.read(join(REPO_ROOT, rel));
  const out: GarmentMesh[] = [];
  for (const mesh of doc.getRoot().listMeshes()) {
    const name = mesh.getName();
    if (name.startsWith("hm08_basemesh")) continue;
    let triangles = 0;
    for (const prim of mesh.listPrimitives()) triangles += (prim.getIndices()?.getCount() ?? 0) / 3;
    // #310: procedural prefixes first — a cover shell whose name happens to start with
    // `makeclothes_library_` is still a deterministic in-repo shell, not a fitted library garment.
    const kind = PROCEDURAL_GENERATORS.some((g) => name.startsWith(g.meshPrefix))
      ? "procedural"
      : name.startsWith(LIBRARY_GARMENT_PREFIX)
        ? "library"
        : "other";
    out.push({ body: rel.split("/").pop()!, mesh: name, triangles: Math.round(triangles), kind });
  }
  return out;
}

/** A library garment resolves when some cached `.mhclo` stem appears in its mesh name. */
function resolvesToCachedSource(meshName: string, stems: ReadonlySet<string>): boolean {
  const normalised = meshName.toLowerCase().replaceAll("-", "_");
  for (const stem of stems) {
    if (stem.length >= 4 && normalised.includes(stem)) return true;
  }
  return false;
}

const measured = (await Promise.all(LIBRARY_BODIES.map(garmentMeshes))).flat();
const cachedStems = everyMhcloStem();

describe("every garment a library body ships can be rebuilt from a source in this repo", () => {
  it(
    "(1) each fitted library garment resolves to a cached .mhclo source — cargo pants and the scrub shirt now resolve; the cover-shell upper is procedural (#310)",
    () => {
      const unreproducible = measured
        .filter((m) => m.kind === "library" && !resolvesToCachedSource(m.mesh, cachedStems))
        .map((m) => `${m.body}: ${m.mesh} (${m.triangles}t) has no source in provider-cache/garments`);
      expect(unreproducible, "shipped garments with no rebuildable source").toEqual([]);
    },
  );

  it("(2) NET COUNTERWEIGHT: each library body still ships an upper AND a lower garment — deleting the unreproducible one is refused", () => {
    for (const rel of LIBRARY_BODIES) {
      const body = rel.split("/").pop()!;
      // #310: procedural uppers (the deterministic cover shell) count as dressing too — the
      // counterweight refuses deleting ANY upper/lower garment from the shipped figure.
      const mine = measured.filter(
        (m) => m.body === body && (m.kind === "library" || m.kind === "procedural"),
      );
      const upper = mine.filter((m) => /shirt|top|gown|scrub|cardigan/i.test(m.mesh));
      const lower = mine.filter((m) => /pants|trouser|skirt|short/i.test(m.mesh));
      expect(upper.length, `${body}: upper garment meshes (${mine.map((m) => m.mesh).join(", ")})`)
        .toBeGreaterThanOrEqual(1);
      expect(lower.length, `${body}: lower garment meshes (${mine.map((m) => m.mesh).join(", ")})`)
        .toBeGreaterThanOrEqual(1);
    }
  });

  it("(3) NET known-good: the footwear meshes ARE reproducible — generated by a script in this repo, no third-party source needed", () => {
    for (const g of PROCEDURAL_GENERATORS) {
      expect(existsSync(join(REPO_ROOT, g.generator)), `${g.generator} exists`).toBe(true);
    }
    const procedural = measured.filter((m) => m.kind === "procedural");
    expect(procedural.length, "procedural garment meshes found").toBeGreaterThanOrEqual(2);
    for (const m of procedural) {
      expect(m.triangles, `${m.body}: ${m.mesh} has geometry`).toBeGreaterThan(0);
    }
  });
});
